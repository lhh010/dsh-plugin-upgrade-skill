// Reproducible vector figures from archived analysis outputs; no new judgments.
import fs from 'node:fs'
import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../..', import.meta.url))
const read = p => JSON.parse(fs.readFileSync(`${root}/${p}`, 'utf8'))
const domains = read('paper/audit/contract-review-20260917/recorded-contracts.json').domains
const panel = read('paper/generated/llm-judge-panel.json')
const labels = ['Version / release', 'API / data / ownership', 'Lifecycle / deployment', 'Safety / boundaries', 'Failure attribution', 'Evidence / verification']
const ds = Object.values(domains)
// Grouped horizontal bars, one per arm, within each contract domain.
const pct = (d, arm) => 100 * d.arms[arm].pass / d.arms[arm].criteria
const yLabels = ds.map((d, i) => '{' + labels[i] + ' ($n=' + d.arms['no-skill'].criteria + '$)}').join(',')
const bars = []
ds.forEach((d, i) => {
  const y = 6 - i
  const no = pct(d, 'no-skill')
  const sk = pct(d, 'with-skill')
  const legend = i === 0 ? 'area legend, ' : ''
  bars.push('\\addplot[' + legend + 'fill=gray!45, draw=gray!70!black, xbar, bar shift=3.4pt] coordinates {(' + no.toFixed(6) + ',' + y + ')};')
  if (i === 0) bars.push('\\addlegendentry{\\textcolor{gray!50!black}{No skill}}')
  bars.push('\\node[font=\\scriptsize, anchor=west] at (axis cs:' + no.toFixed(6) + ',' + y + '+0.19) {' + no.toFixed(1) + '\\%};')
  bars.push('\\addplot[' + legend + 'fill=oiblue, draw=oiblue!70!black, xbar, bar shift=-3.4pt] coordinates {(' + sk.toFixed(6) + ',' + y + ')};')
  if (i === 0) bars.push('\\addlegendentry{\\textcolor{oiblue!80!black}{With skill}}')
  bars.push('\\node[font=\\scriptsize, oiblue!80!black, anchor=west] at (axis cs:' + sk.toFixed(6) + ',' + y + '-0.19) {' + sk.toFixed(1) + '\\%};')
})
const domainTex = String.raw`% Generated by generate-review-figures.mjs; do not edit.
\begin{figure}[t]
\centering
\begin{tikzpicture}
\begin{axis}[
  xbar, bar width=5.5pt, scale only axis, width=10.3cm, height=6.2cm,
  xmin=0, xmax=126, ymin=0.45, ymax=6.55,
  xtick={0,20,40,60,80,100}, ytick={6,5,4,3,2,1},
  yticklabels={${yLabels}},
  tick label style={font=\footnotesize},
  xlabel={Original full-credit decisions (\%)},
  xmajorgrids, grid style={gray!20}, axis lines*=left,
  legend style={at={(1.0,0.02)},anchor=south east,draw=none,font=\footnotesize},
  clip=false]
${bars.join('\n')}
\end{axis}
\end{tikzpicture}
\caption{Original full-credit proportions rise in four contract domains and remain at 100\% in two. Bars summarize all 328 criterion decisions across 64 reports; $n$ is the number of criterion decisions per arm, including both repeats. Both arms reach 100\% in safety/boundaries and failure attribution. These are finite-cohort descriptions of the original judge, not correctness rates or independent samples; the reviewed S11 boundary defect remains despite full original boundary credit.}
\label{fig:contract_credit}
\end{figure}
`
const ids=['glm-5.3-flash','claude-opus-5-5','openai-gpt-5.5','mean of all 3 judges','mean of 2 cross-family judges']
const es=ids.map(id=>{const e=panel.endpoints.find(x=>x.judge===id);assert.ok(e,id);return e})
const styles=['black,mark=square*','oiblue,mark=triangle*','vermillion,mark=diamond*','gray!70!black,mark=o','gray!70!black,mark=o']
const marks=es.map((e,i)=>String.raw`\addplot+[only marks,${styles[i]},mark size=3pt,error bars/.cd,x dir=both,x explicit,error bar style={thick}] coordinates {(${e.meanDelta},${5-i}) += (${e.ci95[1]-e.meanDelta},0) -= (${e.meanDelta-e.ci95[0]},0)};`).join('\n')
const panelTex=String.raw`% Generated by generate-review-figures.mjs; do not edit.
\begin{figure}[t]
\centering
\begin{tikzpicture}
\begin{axis}[
  scale only axis,width=10.3cm,height=5.9cm,
  xmin=-1,xmax=21,ymin=0.5,ymax=5.6,
  xtick={0,5,10,15,20},ytick={5,4,3,2,1},
  yticklabels={{GLM (original)},{Claude Opus 5.5},{GPT-5.5},{All three: mean},{Claude + GPT: mean}},
  tick label style={font=\footnotesize},
  xlabel={Mean paired gain (reward points)},
  xmajorgrids,grid style={gray!20},axis lines*=left]
\addplot[black,dashed,forget plot] coordinates {(0,0.5) (0,5.5)};
\addplot[gray!60,densely dotted,forget plot] coordinates {(-1,2.5) (21,2.5)};
${marks}
\end{axis}
\end{tikzpicture}
\caption{All three judges retain a positive mean gain, while its size depends on the judge. Filled markers show the original GLM score and the two complete LLM re-judgments of the same 64 reports; open markers below the dotted separator average judges within each report and are not additional independent judges. Whiskers are 95\% percentile intervals from 10,000 paired-task bootstrap samples over the same 16 tasks (seed 20260915). All rows share the original rubric and reports; these intervals describe task resampling, not uncertainty over judge populations.}
\label{fig:judge_sensitivity}
\end{figure}
`
for(const [name,text] of Object.entries({'contract-credit-figure.tex':domainTex,'judge-sensitivity-figure.tex':panelTex})){
 const path=`${root}/paper/generated/${name}`
 if(process.argv.includes('--check')) assert.equal(fs.readFileSync(path,'utf8'),text,`drift: ${name}`)
 else fs.writeFileSync(path,text)
}
console.log('Two figures verified against archived domain counts and judge endpoints.')
